#!/usr/bin/env node
/**
 * page-lastmod.mjs — 고정 페이지 사이트맵 lastmod 원천 (NAVER-SEO-FIX-1031, 맥7→맥4 보스 msg 4603·4612·4616)
 *
 *   node scripts/page-lastmod.mjs <config.json>
 *
 * config = { "out": "lib/page-lastmod.generated.ts", "roots": ["app/[locale]"], "paths": ["", "/about", "/offenses/dui", ...],
 *            "files": { "<키>": ["lib/services-data.ts", ...] },            (선택) 키별 원천 파일 묶음
 *            "dirs": [{ "prefix": "ind:", "dir": "content/x", "re": "\\.json$" }] }  (선택) 폴더 안 파일마다 키 = prefix+파일명(확장자 뺌)
 * 경로마다 쪽 파일(<root><path>/page.tsx, 없으면 부모의 [slug]/page.tsx)과 그 파일이 import 하는
 * 데이터·원고 파일(경로에 /data/ /content/ /messages/ 가 든 것, 1단계)의 마지막 커밋 날짜(KST) 중 가장 늦은 날을 쓴다.
 * 커밋 메시지에 [lastmod-skip] 이 있는 커밋은 문구 변경이 아니므로 건너뛴다(f6 build-lastmod.mjs 와 같은 약속).
 * 요청 시각(new Date())은 쓰지 않는다 — 날짜를 못 구하면 빌드를 멈춘다(rc=1).
 */
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname, join, resolve, relative } from 'node:path'

const cfgPath = process.argv[2]
if (!cfgPath) { console.error('usage: page-lastmod.mjs <config.json>'); process.exit(2) }
const ROOT = process.cwd()
const cfg = JSON.parse(readFileSync(cfgPath, 'utf8'))
const EXT = ['', '.ts', '.tsx', '.js', '.mjs', '.json', '/index.ts', '/index.tsx']
const CONTENT_RE = /\/(data|content|messages)\//

function gitDate(files) {
  if (!files.length) return ''
  try {
    return execFileSync('git', ['log', '-1', '--format=%cd', '--date=format-local:%Y-%m-%d',
      '--invert-grep', '--grep=\\[lastmod-skip\\]', '--', ...files], {
      cwd: ROOT, encoding: 'utf8', env: { ...process.env, TZ: 'Asia/Seoul' },
    }).trim()
  } catch { return '' }
}

function resolveImport(from, spec) {
  let base
  if (spec.startsWith('@/')) base = join(ROOT, spec.slice(2))
  else if (spec.startsWith('.')) base = resolve(dirname(from), spec)
  else return null
  for (const e of EXT) {
    const p = base + e
    if (existsSync(p) && statSync(p).isFile()) return p
  }
  return null
}

function pageFile(root, path) {
  const direct = join(ROOT, root, path, 'page.tsx')
  if (existsSync(direct)) return direct
  const parent = join(ROOT, root, dirname(path || '/'))
  for (const dyn of ['[slug]', '[id]', '[...slug]']) {
    const p = join(parent, dyn, 'page.tsx')
    if (existsSync(p)) return p
  }
  return null
}

const out = {}
const errors = []
for (const path of cfg.paths || []) {
  let file = null
  for (const r of cfg.roots) { file = pageFile(r, path); if (file) break }
  if (!file) { errors.push(`쪽 파일 없음: ${path}`); continue }
  const files = [file]
  const src = readFileSync(file, 'utf8')
  for (const m of src.matchAll(/(?:from|import)\s*\(?\s*["']([^"']+)["']/g)) {
    const f = resolveImport(file, m[1])
    if (f && CONTENT_RE.test('/' + relative(ROOT, f))) files.push(f)
  }
  const d = gitDate(files.map((f) => relative(ROOT, f)))
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) { errors.push(`커밋 날짜 없음: ${path} (${relative(ROOT, file)})`); continue }
  out[path] = d
}
for (const [key, files] of Object.entries(cfg.files || {})) {
  const miss = files.filter((f) => !existsSync(join(ROOT, f)))
  if (miss.length) { errors.push(`파일 없음: ${key} ${miss.join(',')}`); continue }
  const d = gitDate(files)
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) { errors.push(`커밋 날짜 없음: ${key}`); continue }
  out[key] = d
}
for (const { prefix, dir, re } of cfg.dirs || []) {
  const rx = new RegExp(re || '.')
  const log = execFileSync('git', ['log', '--format=@@%cd', '--date=format-local:%Y-%m-%d', '--name-only',
    '--invert-grep', '--grep=\\[lastmod-skip\\]', '--', dir], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20, env: { ...process.env, TZ: 'Asia/Seoul' } })
  let cur = ''
  for (const line of log.split('\n')) {
    if (line.startsWith('@@')) { cur = line.slice(2); continue }
    const f = line.trim()
    if (!f || !rx.test(f) || !existsSync(join(ROOT, f))) continue
    const key = prefix + f.slice(dir.replace(/\/$/, '').length + 1).replace(/\.[a-z]+$/, '')
    if (!(key in out)) out[key] = cur
  }
}
if (errors.length) { for (const e of errors) console.error(`FAIL page-lastmod ${e}`); process.exit(1) }
writeFileSync(join(ROOT, cfg.out), `// GENERATED by scripts/page-lastmod.mjs — 손으로 고치지 않는다(쪽 파일·데이터 파일 마지막 커밋일, [lastmod-skip] 제외).
export const PAGE_LASTMOD: Record<string, string> = ${JSON.stringify(out, null, 2)};
`)
console.log(`[page-lastmod] ${Object.keys(out).length}쪽 → ${cfg.out}`)
