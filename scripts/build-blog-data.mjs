/**
 * content/<locale>/*.md(x) → app/data/blog-posts-data.ts 생성.
 * 블로그 상세 페이지는 Cloudflare Worker 런타임에서 fs 를 쓸 수 없으므로
 * 빌드 전에 이 스크립트로 정적 데이터 모듈을 만들어 둔다.
 *
 * 사용: node scripts/build-blog-data.mjs
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import { remark } from "remark";
import remarkGfm from "remark-gfm";
import remarkHtml from "remark-html";

const ROOT = process.cwd();
const CONTENT_ROOT = path.join(ROOT, "content");
const OUT = path.join(ROOT, "app/data/blog-posts-data.ts");
const LOCALES = ["ko", "en", "zh", "ja", "vi"];

function slugsFor(locale) {
  const dir = path.join(CONTENT_ROOT, locale);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".md") || f.endsWith(".mdx"))
    .map((f) => f.replace(/\.(md|mdx)$/, ""));
}

async function toHtml(md) {
  const processed = await remark().use(remarkGfm).use(remarkHtml, { sanitize: false }).process(md);
  return processed.toString();
}

const posts = [];
for (const locale of LOCALES) {
  for (const slug of slugsFor(locale)) {
    const dir = path.join(CONTENT_ROOT, locale);
    const file = [".md", ".mdx"]
      .map((ext) => path.join(dir, slug + ext))
      .find((p) => fs.existsSync(p));
    const raw = fs.readFileSync(file, "utf8");
    const { data, content } = matter(raw);
    posts.push({
      slug,
      locale,
      title: data.title ?? "",
      description: data.description ?? "",
      date: data.date ?? "",
      updated: data.updated ?? data.date ?? "",
      category: data.category ?? "",
      cluster: data.cluster ?? "cluster",
      keywords: data.keywords ?? [],
      related: data.related ?? [],
      faq: data.faq ?? [],
      cover: data.cover ?? "",
      contentHtml: await toHtml(content),
    });
  }
}

posts.sort((a, b) =>
  a.locale === b.locale ? (a.date < b.date ? 1 : -1) : LOCALES.indexOf(a.locale) - LOCALES.indexOf(b.locale)
);

const body = posts
  .map(
    (p) => `  {
    slug: ${JSON.stringify(p.slug)},
    locale: ${JSON.stringify(p.locale)},
    title: ${JSON.stringify(p.title)},
    description: ${JSON.stringify(p.description)},
    date: ${JSON.stringify(p.date)},
    updated: ${JSON.stringify(p.updated)},
    category: ${JSON.stringify(p.category)},
    cluster: ${JSON.stringify(p.cluster)},
    keywords: ${JSON.stringify(p.keywords)},
    related: ${JSON.stringify(p.related)},
    faq: ${JSON.stringify(p.faq)},
    cover: ${JSON.stringify(p.cover)},
    contentHtml: ${JSON.stringify(p.contentHtml)},
  },`
  )
  .join("\n");

const out = `// AUTO-GENERATED by scripts/build-blog-data.mjs — do not edit manually.
export interface BlogPostData {
  slug: string;
  locale: string;
  title: string;
  description: string;
  date: string;
  updated: string;
  category: string;
  cluster: string;
  keywords: string[];
  related: string[];
  faq: { q: string; a: string }[];
  cover: string;
  contentHtml: string;
}

const BLOG_POSTS_DATA: BlogPostData[] = [
${body}
];

export default BLOG_POSTS_DATA;

export function getBlogPostData(slug: string, locale: string): BlogPostData | undefined {
  return BLOG_POSTS_DATA.find((p) => p.slug === slug && p.locale === locale);
}

export function getBlogPostsByLocale(locale: string): BlogPostData[] {
  return BLOG_POSTS_DATA.filter((p) => p.locale === locale);
}

/** hreflang 정확성용 — 해당 slug 의 번역본이 실제로 존재하는 로케일만 반환 */
export function getLocalesForSlug(slug: string): string[] {
  return BLOG_POSTS_DATA.filter((p) => p.slug === slug).map((p) => p.locale);
}

export function getAllBlogSlugs(): string[] {
  return Array.from(new Set(BLOG_POSTS_DATA.map((p) => p.slug)));
}
`;

fs.writeFileSync(OUT, out, "utf8");
const byLocale = LOCALES.map((l) => `${l}:${posts.filter((p) => p.locale === l).length}`).join(" ");
console.log(`blog-posts-data.ts 생성 완료 — 총 ${posts.length}건 (${byLocale})`);
